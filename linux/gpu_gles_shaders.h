static const char GPU_GLES_VERTEX[] =
"#version 300 es\n"
"precision highp float;\n"
"layout(location=0) in vec4 position;\n"
"layout(location=1) in vec2 st;\n"
"layout(location=2) in float fog;\n"
"layout(location=3) in vec4 color;\n"
"uniform vec2 vsize;\n"
"out vec2 v_st;\n"
"out vec4 v_col;\n"
"out vec3 v_affine;\n"
"void main() {\n"
"  vec2 ndc = vec2(position.x / vsize.x * 2.0 - 1.0, 1.0 - position.y / vsize.y * 2.0);\n"
"  // Glide already supplies screen-space depth. Preserve it without a w round trip.\n"
"  gl_Position = vec4(ndc, clamp(position.z, 0.0, 1.0) * 2.0 - 1.0, 1.0);\n"
"  // Projector q can cross zero; preserve its sign through interpolation.\n"
"  float q = position.w;\n"
"  v_st = st * q;\n"
"  v_col = color;\n"
"  v_affine = vec3(q, fog, 1.0);\n"
"}\n";

static const char GPU_GLES_FRAGMENT[] =
"#version 300 es\n"
"precision highp float;\n"
"precision highp int;\n"
"layout(std140) uniform Shade {\n"
"  ivec4 cc; ivec4 ac; ivec4 tcm; ivec4 flags; ivec4 mode;\n"
"  vec4 aref; vec4 chroma; vec4 fogc; vec4 constc; vec4 fogtab4[16];\n"
"};\n"
"uniform sampler2D tex0;\n"
"in vec2 v_st;\n"
"in vec4 v_col;\n"
"in vec3 v_affine;\n"
"out vec4 out_color;\n"
"float saturate(float v) { return clamp(v, 0.0, 1.0); }\n"
"vec3 saturate(vec3 v) { return clamp(v, 0.0, 1.0); }\n"
"float fogtab(int k) { return fogtab4[k >> 2][k & 3]; }\n"
"float fv(int f, float l, float la, float oa, float ta) {\n"
"  int k = f & 7; float v = k == 0 ? 0.0 : k == 1 ? l : k == 2 ? oa : k == 3 ? la : k == 4 ? ta : 1.0;\n"
"  return ((f & 8) != 0) ? 1.0 - v : v; }\n"
"float comb(int fn, float f, float l, float la, float o) {\n"
"  if (fn == 0) return 0.0; if (fn == 1) return l; if (fn == 2) return la; if (fn == 3) return f * o;\n"
"  if (fn == 4) return f * o + l; if (fn == 5) return f * o + la; if (fn == 6) return f * (o - l);\n"
"  if (fn == 7) return f * (o - l) + l; if (fn == 8) return f * (o - l) + la; if (fn == 9) return l - f * l;\n"
"  if (fn == 16) return la - f * l; return l; }\n"
"float fog_w(float w) {\n"
"  if (w <= 1.0) return fogtab(0);\n"
"  float q = floor(log2(w)); float m = w / exp2(q);\n"
"  int r = m < 1.142857 ? 0 : m < 1.333333 ? 1 : m < 1.6 ? 2 : 3;\n"
"  int i = int(q) * 4 + r; if (i >= 63) return fogtab(63);\n"
"  int j = i + 1;\n"
"  float wi = exp2(3.0 + float(i >> 2)) / float(8 - (i & 3));\n"
"  float wj = exp2(3.0 + float(j >> 2)) / float(8 - (j & 3));\n"
"  return mix(fogtab(i), fogtab(j), saturate((w - wi) / (wj - wi))); }\n"
"void main() {\n"
"  vec4 it = v_col / v_affine.z;\n"
"  float oow = v_affine.x / v_affine.z;\n"
"  float fog = v_affine.y / v_affine.z;\n"
"  vec4 tx = vec4(1, 1, 1, 1);\n"
"  if (mode.x != 0) {\n"
"    if (oow <= 0.0) discard;\n"
"    vec4 t = texture(tex0, v_st / oow);\n"
"    if (mode.z != 0 && all(lessThan(abs(t.rgb - chroma.rgb), vec3(0.5 / 255.0)))) discard;\n"
"    tx.r = comb(tcm.x, fv(tcm.y, t.r, t.a, 0.0, t.a), t.r, t.a, 0.0);\n"
"    tx.g = comb(tcm.x, fv(tcm.y, t.g, t.a, 0.0, t.a), t.g, t.a, 0.0);\n"
"    tx.b = comb(tcm.x, fv(tcm.y, t.b, t.a, 0.0, t.a), t.b, t.a, 0.0);\n"
"    tx.a = comb(tcm.z, fv(tcm.w, t.a, t.a, 0.0, t.a), t.a, t.a, 0.0);\n"
"    if (flags.z != 0) tx.rgb = 1.0 - tx.rgb; if (flags.w != 0) tx.a = 1.0 - tx.a;\n"
"  }\n"
"  float la = ac.z == 1 ? constc.a : it.a;\n"
"  float oa = ac.w == 1 ? tx.a : ac.w == 2 ? constc.a : it.a;\n"
"  float outa = comb(ac.x, fv(ac.y, la, la, oa, tx.a), la, la, oa);\n"
"  if (flags.y != 0) outa = 1.0 - outa; outa = saturate(outa);\n"
"  vec4 lc = cc.z == 1 ? constc : it;\n"
"  vec4 oc = cc.w == 1 ? tx : cc.w == 2 ? constc : it;\n"
"  vec3 o;\n"
"  o.r = comb(cc.x, fv(cc.y, lc.r, la, oa, tx.a), lc.r, la, oc.r);\n"
"  o.g = comb(cc.x, fv(cc.y, lc.g, la, oa, tx.a), lc.g, la, oc.g);\n"
"  o.b = comb(cc.x, fv(cc.y, lc.b, la, oa, tx.a), lc.b, la, oc.b);\n"
"  if (flags.x != 0) o = 1.0 - o;\n"
"  o = saturate(o);\n"
"  if (mode.z != 0 && mode.x == 0 && all(lessThan(abs(o - chroma.rgb), vec3(0.5 / 255.0)))) discard;\n"
"  float av = floor(outa * 255.0 + 0.001), rv = floor(aref.x * 255.0 + 0.5); bool ok = true;\n"
"  int at = mode.y;\n"
"  if (at == 0) ok = false; else if (at == 1) ok = av < rv; else if (at == 2) ok = av == rv;\n"
"  else if (at == 3) ok = av <= rv; else if (at == 4) ok = av > rv; else if (at == 5) ok = av != rv;\n"
"  else if (at == 6) ok = av >= rv;\n"
"  if (!ok) discard;\n"
"  if (mode.w != 0) {\n"
"    float f = mode.w == 1 ? fog : mode.w == 4 ? it.a : mode.w == 3 ? 0.0 : fog_w(oow > 1e-7 ? 1.0 / oow : 65535.0);\n"
"    o = mix(o, fogc.rgb, saturate(f));\n"
"  }\n"
"  out_color = vec4(o, outa); }\n";

